# 6. ВЕКТОР МИРА (Фаза 4) — аналог вектора развития персонажа.
# ─────────────────────────────────────────────────────────────────────────
def _gap_tier(v):
    if v < -18: return "мир недооценивает себя (скрытая сила/потенциал)"
    if v < -6:  return "мир слегка недооценивает себя"
    if v < 10:  return "трезвая самооценка эпохи"
    if v < 24:  return "мир переоценивает себя (гордыня/инерция славы)"
    return "мир сильно переоценивает себя (имперский мираж — крах ближе, чем кажется)"

def roll_vector(rng):
    level = wchoice(rng, [("плато", 38), ("упадок", 24), ("восхождение", 20),
                          ("на изломе", 13), ("застой", 5)])
    gap = rng.gauss(6, 18)
    return {"level": level, "gap_value": round(gap), "gap_tier": _gap_tier(gap),
            "rare": level in ("на изломе",)}


