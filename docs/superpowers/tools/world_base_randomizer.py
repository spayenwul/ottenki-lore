def _density_label(total, need):
    if total >= need * 1.3: return "насыщенно (плотность выше нормы масштаба)"
    if total >= need:       return "достаточно для масштаба"
    if total >= need * 0.6: return "ТОНКОВАТО — на грани «полторы фракции»"
    return "ПУСТО — «полторы фракции на огромный мир» (добери акторов!)"

def roll_ecology(rng, great_n, scale):
    m = SCALE_MULT.get(scale, SCALE_MULT["континент"])
    regions = rng.randint(3, 6) if scale == "мир" else 1
    great = great_n * regions           # для «мир»: great_n трактуется как «на регион»
    mid = round(great * rng.uniform(*m["mid"]))
    minr = round(great * rng.uniform(*m["min"]))
    non = round(great * rng.uniform(*m["non"]))
    total = great + mid + minr          # госполитии (без негос. акторов)
    return {"scale": scale, "regions": regions, "great": great, "middle": mid,
            "minor": minr, "nonstate": non, "total_polities": total,
            "need": m["need"], "verdict": _density_label(total, m["need"])}


