def _fortune_band(die):
    if die <= 2: return ("катастрофа/бедствие", "≈ 2:1 в сторону беды")
    if die <= 4: return ("ровная эпоха", "≈ 1:1 благо/беда")
    return ("золотой век", "≈ 2:1 в сторону блага")

def roll_fortune(rng):
    out = []
    for e in EPOCHS:
        die = rng.randint(1, 6)
        band, tilt = _fortune_band(die)
        out.append({"epoch": e, "die": die, "band": band, "tilt": tilt})
    return out


