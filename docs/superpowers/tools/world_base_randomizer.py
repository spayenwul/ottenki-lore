def _band(key, v):
    for lo, hi, state, eff in BANDS[key]:
        if lo <= v <= hi:
            return state, eff
    return "вне шкалы", ""

def roll_substrate(rng):
    chan = {}
    for k in ORDER:
        v = round(clamp(rng.gauss(MU, SIGMA)))
        z = (v - MU) / SIGMA
        state, eff = _band(k, v)
        chan[k] = {"value": v, "z": z, "tier": _tier(z), "dir": _dir(z),
                   "state": state, "effect": eff, "name": NAMES[k]}
    return chan


