def roll_factions(rng):
    n = wchoice(rng, [(2, 15), (3, 30), (4, 30), (5, 15), (6, 10)])
    disps = rng.sample(DISPOSITIONS, min(n, len(DISPOSITIONS)))
    out = []
    for i in range(n):
        out.append({"disposition": disps[i] if i < len(disps) else rng.choice(DISPOSITIONS),
                    "posture": wchoice(rng, POSTURE),
                    "resource": rng.choice(RES_REL)})
    return {"count": n, "list": out}


