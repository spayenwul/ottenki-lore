def clamp(x, lo=0.0, hi=100.0):
    return max(lo, min(hi, x))

def wchoice(rng, pairs):
    total = sum(w for _, w in pairs)
    r = rng.random() * total
    upto = 0.0
    for item, w in pairs:
        upto += w
        if r <= upto:
            return item
    return pairs[-1][0]

Z_OBYDENNO = 1.44
Z_ZAMETNO  = 2.50
Z_VYDAY    = 3.30
MU, SIGMA = 50.0, (70.0 - 30.0) / 2.0 / Z_OBYDENNO  # ~13.89 → ±20 ≈ 85%

def _tier(z):
    a = abs(z)
    if a < Z_OBYDENNO: return "обыденно"
    if a < Z_ZAMETNO:  return "заметно"
    if a < Z_VYDAY:    return "выдающееся"
    return "граничное"

def _dir(z):
    return "выше" if z > 0 else "ниже"


