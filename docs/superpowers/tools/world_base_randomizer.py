    L.append("  Крупные силы детализируй; средние/малые/негос. — считанное число,"
             " раскрывай по мере надобности (не оставляй мир пустым).")

    vt = w["verticality"]
    L.append("\nВЕРТИКАЛЬ СИЛЫ · КАРМАНЫ · УГРОЗЫ (жанр «{}»):".format(vt["genre"]))
