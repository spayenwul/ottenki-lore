def generate(rng, scale="континент", genre="обычный"):
    # Порядок потребления rng фиксирован (derived rng не трогает) → сиды
    # прежних прогонов воспроизводимы; ecology и verticality катятся ПОСЛЕДНИМИ.
    chan = roll_substrate(rng)
    dvd = derived(chan)
    fortune = roll_fortune(rng)
    fac = roll_factions(rng)
    truth = roll_truth_sheet(rng)
    vec = roll_vector(rng)
    eco = roll_ecology(rng, fac["count"], scale)
    vert = roll_verticality(rng, genre)
    return {"substrate": chan, "derived": dvd, "fortune": fortune,
            "factions": fac, "truth_sheet": truth, "vector": vec,
            "ecology": eco, "verticality": vert}

