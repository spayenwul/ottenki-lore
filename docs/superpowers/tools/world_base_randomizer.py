def roll_verticality(rng, genre):
    g = GENRE.get(genre, GENRE["обычный"])
    ct = wchoice(rng, g["ceil"])
    ceil = next(c for c in CEILING if c[0] == ct)
    if g["steep"]:
        steep = wchoice(rng, [("крутая — немного на вершине", 3),
                              ("предельная — единицы держат всё", 2), ("пологая — много сильных", 1)])
    else:
        steep = wchoice(rng, [("пологая — много сильных", 2),
                              ("крутая — немного на вершине", 2), ("предельная — единицы держат всё", 1)])
    realms = rng.randint(*g["rl"])
    pockets = rng.randint(*g["pk"])
    apex_n = rng.randint(*g["ap"])
    return {"genre": genre, "ceiling_tier": ct, "ceiling": ceil[1], "ceiling_eff": ceil[2],
            "steepness": steep, "realms": realms,
            "pockets": pockets,
            "pocket_types": rng.sample(POCKET_TYPES, min(pockets, len(POCKET_TYPES))) if pockets else [],
            "apex_count": apex_n,
            "apex_types": rng.sample(APEX_TYPES, min(apex_n, len(APEX_TYPES))) if apex_n else []}


