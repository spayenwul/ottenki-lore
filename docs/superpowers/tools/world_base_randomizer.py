def selftest():
    ok = True
    def check(cond, msg):
        nonlocal ok
        if not cond: ok = False
        print("  [{}] {}".format("OK " if cond else "FAIL", msg))
    check(_tier(0.0) == "обыденно" and _tier(2.0) == "заметно"
          and _tier(3.0) == "выдающееся" and _tier(4.0) == "граничное", "тиры по z")
    check(_band("RES", 10)[0] == "скудный мир" and _band("RES", 95)[0] == "изобильный", "бэнды RES")
    check(_band("CNC", 90)[0] == "в одной точке", "CNC монополия")
    check(_fortune_band(1)[0].startswith("катастроф") and _fortune_band(6)[0] == "золотой век",
          "рок эпох")
    a = generate(random.Random(902)); b = generate(random.Random(902))
    check(json.dumps(a, ensure_ascii=False, sort_keys=True) == json.dumps(b, ensure_ascii=False, sort_keys=True),
          "детерминизм по seed")
    d = derived({k: {"value": 50} for k in ORDER})
    check(all(0 <= x <= 100 for x in d.values()), "деривативы в границах")
    fac = roll_factions(random.Random(1))
    check(2 <= fac["count"] <= 6 and len(fac["list"]) == fac["count"], "фракции 2..6")
    eco = roll_ecology(random.Random(1), 4, "континент")
    check(eco["total_polities"] > eco["great"] and eco["minor"] >= eco["great"],
          "экология: малых больше крупных, всего > крупных")
    ew = roll_ecology(random.Random(1), 4, "мир")
    check(ew["regions"] >= 3 and ew["great"] >= 12, "масштаб «мир»: регионы×крупные силы")
    rv = roll_verticality(random.Random(3), "сянься")
    check(rv["realms"] >= 5 and rv["pockets"] >= 4 and rv["ceiling_tier"] >= 2,
          "сянься: ступени/карманы/высокий потолок")
    ro = roll_verticality(random.Random(3), "обычный")
    check(ro["ceiling_tier"] <= 4, "обычный жанр: потолок в границах")
    # сид 902 воспроизводим (ecology катится последней, прежние роллы не сдвинуты)
    w1 = generate(random.Random(902)); w2 = generate(random.Random(902))
    check(w1["factions"] == w2["factions"] and w1["ecology"] == w2["ecology"],
          "детерминизм с экологией")
    print("\nSELFTEST:", "ВСЁ OK" if ok else "ЕСТЬ ПРОВАЛЫ")
    return 0 if ok else 1

def main(argv=None):
    ap = argparse.ArgumentParser(description="Рандомизатор субстрата для генератора миров «Пласты Мира».")
    ap.add_argument("--seed", type=int, default=None)
    ap.add_argument("--scale", choices=["регион", "континент", "мир"], default="континент",
                    help="масштаб генерируемого пространства (задаёт плотность фракций)")
    ap.add_argument("--genre", choices=["обычный", "сянься", "мифический"], default="обычный",
                    help="жанр: сдвигает потолок силы, карманы пространства и верхние угрозы")
    ap.add_argument("--all", action="store_true", help="показать всё (однопроходный режим)")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args(argv)
    if args.selftest:
        return selftest()
    rng = random.Random(args.seed)
    w = generate(rng, args.scale, args.genre)
    if args.json:
        print(json.dumps(w, ensure_ascii=False, indent=2))
    else:
        print(PREAMBLE)
        print(render(w))
    return 0

if __name__ == "__main__":
    sys.exit(main())
